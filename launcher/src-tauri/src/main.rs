// PantryOS desktop launcher (ADR 0018 §4/§7).
//
// The product's face on desktop: detects Docker, generates the instance
// config (secrets never shown to the user), starts the compose stack, waits
// for health, and opens the browser. Docker is never named in the UI outside
// diagnostics. The update transaction itself belongs to the in-stack
// supervisor (ADR 0018 §6) — this app is a remote control, not the engine.

#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

use base64::Engine;
use rand::RngCore;
use serde::Serialize;
use std::fs;
use std::net::TcpListener;
use std::path::PathBuf;
use std::process::Command;
use std::time::{Duration, Instant};

const COMPOSE_TEMPLATE: &str = include_str!("../compose/docker-compose.product.yml");
const DEFAULT_PORT: u16 = 8420;
const HEALTH_TIMEOUT_SECS: u64 = 300; // first run pulls images

#[derive(Serialize)]
struct DockerStatus {
    installed: bool,
    running: bool,
    detail: String,
}

#[derive(Serialize)]
struct StackStatus {
    installed: bool,
    healthy: bool,
    port: u16,
    url: String,
}

#[derive(Serialize)]
struct InstallResult {
    url: String,
    port: u16,
    reused_existing: bool,
}

fn docker(args: &[&str]) -> Result<String, String> {
    let output = Command::new("docker")
        .args(args)
        .output()
        .map_err(|e| format!("docker not runnable: {e}"))?;
    if output.status.success() {
        Ok(String::from_utf8_lossy(&output.stdout).to_string())
    } else {
        Err(String::from_utf8_lossy(&output.stderr).to_string())
    }
}

fn config_dir() -> Result<PathBuf, String> {
    let base = dirs::config_dir().ok_or("no config directory on this platform")?;
    let dir = base.join("pantryos");
    fs::create_dir_all(&dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    Ok(dir)
}

fn urlsafe_b64(bytes: &[u8]) -> String {
    base64::engine::general_purpose::URL_SAFE.encode(bytes)
}

fn generate_env(port: u16) -> String {
    let mut pg = [0u8; 24];
    rand::rngs::OsRng.fill_bytes(&mut pg);
    let mut fernet = [0u8; 32];
    rand::rngs::OsRng.fill_bytes(&mut fernet);
    let pg_hex: String = pg.iter().map(|b| format!("{b:02x}")).collect();
    format!(
        "# Generated by the PantryOS launcher — do not edit while the app is running.\n\
         POSTGRES_PASSWORD={pg_hex}\n\
         CONFIG_SECRET_KEY={fernet_key}\n\
         PANTRYOS_PORT={port}\n\
         AUTH_ENABLED=false\n",
        fernet_key = urlsafe_b64(&fernet),
    )
}

fn read_env_port(env_path: &PathBuf) -> Option<u16> {
    let text = fs::read_to_string(env_path).ok()?;
    text.lines()
        .find_map(|l| l.strip_prefix("PANTRYOS_PORT="))
        .and_then(|v| v.trim().parse().ok())
}

fn pick_free_port() -> u16 {
    for port in DEFAULT_PORT..DEFAULT_PORT + 20 {
        if TcpListener::bind(("127.0.0.1", port)).is_ok() {
            return port;
        }
    }
    DEFAULT_PORT
}

fn compose(dir: &PathBuf, args: &[&str]) -> Result<String, String> {
    let compose_path = dir.join("docker-compose.product.yml");
    let env_path = dir.join(".env");
    let mut full: Vec<String> = vec![
        "compose".into(),
        "--project-directory".into(),
        dir.display().to_string(),
        "--env-file".into(),
        env_path.display().to_string(),
        "-f".into(),
        compose_path.display().to_string(),
    ];
    full.extend(args.iter().map(|s| s.to_string()));
    let refs: Vec<&str> = full.iter().map(String::as_str).collect();
    docker(&refs)
}

fn health_ok(port: u16) -> bool {
    ureq::get(&format!("http://127.0.0.1:{port}/health"))
        .timeout(Duration::from_secs(3))
        .call()
        .map(|r| r.status() == 200)
        .unwrap_or(false)
}

#[tauri::command]
fn docker_status() -> DockerStatus {
    match docker(&["info", "--format", "{{.ServerVersion}}"]) {
        Ok(v) => DockerStatus {
            installed: true,
            running: true,
            detail: format!("Docker engine {}", v.trim()),
        },
        Err(err) => {
            let installed = Command::new("docker").arg("--version").output().is_ok();
            DockerStatus {
                installed,
                running: false,
                detail: if installed {
                    format!("Docker is installed but not running: {}", err.trim())
                } else {
                    "Docker is not installed.".into()
                },
            }
        }
    }
}

#[tauri::command]
fn install_stack() -> Result<InstallResult, String> {
    let dir = config_dir()?;
    let env_path = dir.join(".env");

    // Re-runs must preserve existing secrets (and the data keyed to them).
    let reused_existing = env_path.exists();
    let port = if reused_existing {
        read_env_port(&env_path).unwrap_or(DEFAULT_PORT)
    } else {
        let port = pick_free_port();
        fs::write(&env_path, generate_env(port))
            .map_err(|e| format!("cannot write config: {e}"))?;
        port
    };
    fs::write(dir.join("docker-compose.product.yml"), COMPOSE_TEMPLATE)
        .map_err(|e| format!("cannot write compose file: {e}"))?;

    compose(&dir, &["pull"]).map_err(|e| format!("Downloading PantryOS failed: {e}"))?;
    compose(&dir, &["up", "-d"]).map_err(|e| format!("Starting PantryOS failed: {e}"))?;

    let deadline = Instant::now() + Duration::from_secs(HEALTH_TIMEOUT_SECS);
    while Instant::now() < deadline {
        if health_ok(port) {
            return Ok(InstallResult {
                url: format!("http://localhost:{port}"),
                port,
                reused_existing,
            });
        }
        std::thread::sleep(Duration::from_secs(3));
    }
    Err(format!(
        "PantryOS started but did not become healthy within {HEALTH_TIMEOUT_SECS}s. \
         Use 'Collect diagnostics' and check the logs."
    ))
}

#[tauri::command]
fn stack_status() -> StackStatus {
    let port = config_dir()
        .ok()
        .and_then(|d| read_env_port(&d.join(".env")))
        .unwrap_or(DEFAULT_PORT);
    let installed = config_dir()
        .map(|d| d.join(".env").exists())
        .unwrap_or(false);
    StackStatus {
        installed,
        healthy: health_ok(port),
        port,
        url: format!("http://localhost:{port}"),
    }
}

#[tauri::command]
fn stop_stack() -> Result<String, String> {
    compose(&config_dir()?, &["stop"])
}

#[tauri::command]
fn start_stack() -> Result<String, String> {
    compose(&config_dir()?, &["up", "-d"])
}

#[tauri::command]
fn diagnostics() -> Result<String, String> {
    let dir = config_dir()?;
    let logs = compose(&dir, &["logs", "--tail", "200"]).unwrap_or_else(|e| e);
    let ps = compose(&dir, &["ps"]).unwrap_or_else(|e| e);
    // No secrets: .env is deliberately NOT included.
    Ok(format!(
        "== docker compose ps ==\n{ps}\n== logs (last 200) ==\n{logs}"
    ))
}

#[tauri::command]
fn open_app(url: String) -> Result<(), String> {
    if !url.starts_with("http://") && !url.starts_with("https://") {
        return Err("refusing to open a non-http URL".into());
    }
    open::that(url).map_err(|e| e.to_string())
}

fn main() {
    tauri::Builder::default()
        .invoke_handler(tauri::generate_handler![
            docker_status,
            install_stack,
            stack_status,
            stop_stack,
            start_stack,
            diagnostics,
            open_app
        ])
        .run(tauri::generate_context!())
        .expect("error while running the PantryOS launcher");
}
