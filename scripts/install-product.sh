#!/usr/bin/env bash
# PantryOS one-command install for Linux / NAS / Raspberry Pi (ADR 0018 §7).
# Windows/macOS users should prefer the desktop launcher; this script is the
# documented path for headless boxes:
#
#   curl -fsSL https://raw.githubusercontent.com/Wildstone-Systems/wildstone-pantry/main/scripts/install-product.sh | bash
#
# It generates secrets, writes the product compose file + env into
# $PANTRYOS_HOME (default ~/.pantryos), starts the stack, waits for health,
# and prints the LAN address. Re-running preserves existing secrets/data.
# Set DRY_RUN=1 to print what would happen without touching Docker.

set -euo pipefail

PANTRYOS_HOME="${PANTRYOS_HOME:-$HOME/.pantryos}"
PANTRYOS_PORT="${PANTRYOS_PORT:-8420}"
PANTRYOS_IMAGE="${PANTRYOS_IMAGE:-ghcr.io/wildstone-systems/pantryos:stable}"
COMPOSE_URL="${COMPOSE_URL:-https://raw.githubusercontent.com/Wildstone-Systems/wildstone-pantry/main/docker-compose.product.yml}"
DRY_RUN="${DRY_RUN:-0}"

say() { echo "[pantryos] $*"; }
die() { echo "[pantryos] ERROR: $*" >&2; exit 1; }

run() {
  if [ "$DRY_RUN" = "1" ]; then
    say "DRY_RUN: $*"
  else
    "$@"
  fi
}

# 1. Prerequisites -------------------------------------------------------------
command -v docker >/dev/null 2>&1 || die "Docker is required. Install it first: https://get.docker.com"
if [ "$DRY_RUN" != "1" ]; then
  docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (the 'docker compose' plugin)."
  docker info >/dev/null 2>&1 || die "Docker is installed but not running (or you lack permission — try the docker group)."
fi

# 2. Config directory + secrets (preserved across re-runs) ----------------------
mkdir -p "$PANTRYOS_HOME"
ENV_FILE="$PANTRYOS_HOME/.env"
COMPOSE_FILE="$PANTRYOS_HOME/docker-compose.product.yml"

gen_fernet_key() {
  # 32 random bytes, urlsafe base64 — a valid Fernet key without needing Python.
  head -c 32 /dev/urandom | base64 | tr '+/' '-_'
}

if [ ! -f "$ENV_FILE" ]; then
  say "Generating configuration in $PANTRYOS_HOME"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by install-product.sh — keep this file; it holds your database secrets.
POSTGRES_PASSWORD=$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')
CONFIG_SECRET_KEY=$(gen_fernet_key)
PANTRYOS_PORT=$PANTRYOS_PORT
PANTRYOS_IMAGE=$PANTRYOS_IMAGE
AUTH_ENABLED=false
EOF
else
  say "Reusing existing configuration in $PANTRYOS_HOME (secrets preserved)"
  PANTRYOS_PORT=$(grep -E '^PANTRYOS_PORT=' "$ENV_FILE" | cut -d= -f2 || echo "$PANTRYOS_PORT")
fi

# 3. Compose file (refreshed each run; pinned by env) ---------------------------
if [ -f "$(dirname "$0")/../docker-compose.product.yml" ]; then
  cp "$(dirname "$0")/../docker-compose.product.yml" "$COMPOSE_FILE"
else
  say "Fetching compose file"
  run curl -fsSL "$COMPOSE_URL" -o "$COMPOSE_FILE"
fi

# 4. Start ---------------------------------------------------------------------
say "Downloading and starting PantryOS (first run can take a few minutes)"
run docker compose --project-directory "$PANTRYOS_HOME" --env-file "$ENV_FILE" -f "$COMPOSE_FILE" pull
run docker compose --project-directory "$PANTRYOS_HOME" --env-file "$ENV_FILE" -f "$COMPOSE_FILE" up -d

# 5. Health wait ----------------------------------------------------------------
if [ "$DRY_RUN" != "1" ]; then
  say "Waiting for PantryOS to come up on port $PANTRYOS_PORT ..."
  for _ in $(seq 1 100); do
    if curl -fsS "http://127.0.0.1:$PANTRYOS_PORT/health" >/dev/null 2>&1; then
      break
    fi
    sleep 3
  done
  curl -fsS "http://127.0.0.1:$PANTRYOS_PORT/health" >/dev/null 2>&1 \
    || die "PantryOS did not become healthy. Check: docker compose --project-directory $PANTRYOS_HOME -f $COMPOSE_FILE logs"
fi

# 6. Where to find it -----------------------------------------------------------
LAN_IP=$(hostname -I 2>/dev/null | awk '{print $1}' || true)
say "PantryOS is running."
say "  This machine:  http://localhost:$PANTRYOS_PORT"
[ -n "${LAN_IP:-}" ] && say "  Your network:  http://$LAN_IP:$PANTRYOS_PORT   (open this on phones/tablets)"
say "Finish setup in the browser — the first-run wizard takes it from there."
