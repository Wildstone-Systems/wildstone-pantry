"""Rebuild inventory projections from the event log (ADR 0002).

The correctness backstop: ``inv_balance`` / ``inv_lot`` can always be
regenerated by replaying ``inventory_events`` in ``seq`` order. Projection
writes happen synchronously in the caller's transaction.
"""

from __future__ import annotations

import uuid
from decimal import Decimal

from sqlalchemy.orm import Session

from modules.inventory import repository
from modules.inventory.domain.lots import replay_lots
from modules.inventory.projections import replay_balances


def rebuild_projections(db: Session) -> dict[str, int]:
    """Replay the whole event log into the projection tables.

    Returns a small summary (counts) for callers/scripts.
    """
    events = [repository.to_event_data(row) for row in repository.iter_events(db)]
    last_seq = max((e.seq for e in events), default=0)

    balances = replay_balances(events)
    lots = replay_lots(events)

    # Track the most recent unit seen per (item, location) for the balance rows.
    units: dict[tuple[uuid.UUID, uuid.UUID], str] = {}
    for e in events:
        if e.location_id is not None:
            units[(e.item_id, e.location_id)] = e.unit
        if e.target_location_id is not None:
            units[(e.item_id, e.target_location_id)] = e.unit

    # Drop zero balances — they carry no information in the projection.
    nonzero = {key: qty for key, qty in balances.items() if qty != Decimal("0")}
    live_lots = [lot for lot in lots.values() if lot.quantity_remaining > 0]

    repository.write_projections(db, balances=nonzero, units=units, lots=live_lots, last_seq=last_seq)
    db.flush()
    return {"events": len(events), "balances": len(nonzero), "lots": len(live_lots), "last_seq": last_seq}
